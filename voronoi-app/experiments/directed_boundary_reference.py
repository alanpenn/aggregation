"""Six-page exact L-room reference for the physical-boundary crawler."""
import argparse
from fractions import Fraction as F
from pathlib import Path

import pymupdf
from shapely.geometry import Polygon, box

from experiments.directed_boundary_cover import Crawler
from experiments.flat40_exchange_atlas import combine, foot, label, page, plot_pdf, polygon, xy
from experiments.flat40_region257_inspection import convex_intersection, exact_area, packed
from voronoi_app.batch_store import encode
from voronoi_app.region_incidence_angular import halfplanes

L_ROOM=Polygon([(0,0),(6,0),(6,2),(2,2),(2,6),(0,6)])
LOW=((0,0),(6,0),(6,2),(0,2))
UP=((0,0),(2,0),(2,6),(0,6))


def base(ax, crawler):
    polygon(ax,L_ROOM,"#edf3ef","#203b3a",1.2,z=1)
    for f in crawler.faces:
        centre=tuple((a+b)/2 for a,b in zip(f.a,f.b))
        label(ax,xy(centre),f"W{f.identifier+1}","#304744",size=9)
    ax.scatter(2,2,s=30,c="#be542c",zorder=9)
    label(ax,(2,2),"Re-entrant (2, 2)","#be542c",offset=(6,8))
    ax.set(xlim=(-.8,6.85),ylim=(-.7,6.7),aspect="equal")
    ax.set_xticks(range(7))
    ax.set_yticks(range(7))
    ax.spines[["top","right"]].set_visible(False)


def draw_walk(ax, attempt):
    for item in attempt["path"]:
        if item["type"] not in {"physical_face","straight_extension"}:
            continue
        a,b=map(xy,item["interval"])
        extension=item["type"]=="straight_extension"
        c="#bf5128" if extension else "#225d89"
        ax.plot(*zip(a,b),color=c,lw=2.3,zorder=5,
                linestyle="dashed" if extension else "solid")
        q=tuple(x+.55*(y-x) for x,y in zip(a,b))
        r=tuple(x+.73*(y-x) for x,y in zip(a,b))
        ax.annotate("",xy=r,xytext=q,arrowprops={"arrowstyle":"-|>","color":c,"lw":2},zorder=6)
        if extension:
            label(ax,q,"Straight extension",c,offset=(-28,-14))


def main(output):
    crawler=Crawler(L_ROOM)
    regions,attempts,stats=crawler.construct()
    if set(regions)!={LOW,UP} or any(exact_area(list(r))!=12 for r in regions):
        raise ValueError("Reference rectangles did not close.")
    overlap=exact_area(convex_intersection(list(LOW),halfplanes(list(UP)+[UP[0]])))
    if overlap!=4 or 24-overlap!=F(L_ROOM.area):
        raise ValueError("Reference coverage or overlap disagrees.")
    low=attempts[regions[LOW][0]]
    up=attempts[regions[UP][0]]
    output.mkdir(parents=True,exist_ok=False)
    sources=[]
    def add(title,subtitle,render,panels=1):
        fig,axes=page(title,subtitle,panels)
        for ax in axes:
            base(ax,crawler)
        render(axes)
        if panels==1:
            foot(fig,"Exact wall and extension positions in model units")
        path=output/f"{len(sources)+1:02d}.pdf"
        plot_pdf(path,[fig])
        sources.append((title,path))

    add("L-room physical boundary","Five 90° corners and one 270° corner",lambda a:None)
    add("Anticlockwise · right hand on wall","Continue west at (2, 2) until reaching W6",
        lambda a:draw_walk(a[0],low))
    add("Clockwise · left hand on wall","Continue south at (2, 2) until reaching W1",
        lambda a:draw_walk(a[0],up))
    def separate(a):
        for ax,p,title in zip(a,(LOW,UP),("[0,6] × [0,2]","[0,2] × [0,6]")):
            polygon(ax,Polygon(p),"#8bbd99","#267344",1.25,z=2,alpha=.5)
            ax.set_title(title)
    add("The two exact rectangles","Both were generated by physical-wall walks",separate,2)
    def combined(a):
        for p in (LOW,UP):
            polygon(a[0],Polygon(p),"#2d8964","#20734f",1.15,z=2,alpha=.31)
    add("Overlapping convex cover","Identical translucent fill for each rectangle",combined)
    def density(a):
        ax=a[0]
        for p,amount in ((box(0,0,2,2),2),(box(2,0,6,2),1),(box(0,2,2,6),1)):
            polygon(ax,p,"#398972" if amount==2 else "#bbdccc","#23694e",.9,z=2)
            label(ax,p.centroid.coords[0],amount,"#173f3c")
    add("Exact overlap multiplicity","Area at count one = 16 · area at count two = 4 · uncovered area = 0",density)
    atlas=output/"l_room_directed_boundary_atlas.pdf"
    combine(atlas,sources)
    with pymupdf.open(atlas) as pdf:
        if len(pdf)!=6 or any(p.get_images() for p in pdf):
            raise ValueError("Expected six vector pages.")
    (output/"exact-reference.json").write_bytes(encode({"domain":packed([f.a for f in crawler.faces]),
        "area":"20","covered":"20","uncovered":"0","area_by_multiplicity":{"1":"16","2":"4"},
        "regions":[{"vertices":packed(shape),"generating_attempts":ids} for shape,ids in regions.items()],
        "faces":crawler.face_records(),"attempts":attempts,"statuses":dict(stats)}))


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output",type=Path,required=True)
    main(parser.parse_args().output)
